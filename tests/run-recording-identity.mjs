// Node 22+ runner. No packages. Optional --browser uses an isolated Edge profile.
// --generate-fixtures reads the sibling iMuse exporter but never writes there.
import { readFile, writeFile, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve, sep } from 'node:path';
import { tmpdir } from 'node:os';
import { createServer } from 'node:http';
import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fixturePath = join(root, 'tests', 'fixtures', 'imuse-recording-identity.json');
if (process.argv.includes('--generate-fixtures')) {
    const source = await readFile(resolve(root, '../iMuse/js/recording-identity.js'), 'utf8');
    const exporter = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
    const f = await import('./recording-identity-fixtures.js');
    const files = [];
    for (const [name, original] of [['m4a', f.mp4()], ['webm', f.webm([], { unknownCluster: true })], ['wav', f.wav()], ['ogg-opus', f.ogg([], { large: true })], ['ogg-vorbis', f.ogg([], { vorbis: true })]]) {
        const exported = await exporter.embedRecordingIdentity(original, f.ID);
        if ((await exporter.readRecordingIdentity(exported)).recordingId !== f.ID) throw Error('Exporter readback failed: ' + name);
        const repeated = await exporter.embedRecordingIdentity(exported, f.ID);
        if (repeated !== exported) throw Error('Repeated export changed fixture: ' + name);
        files.push({ name, base64: Buffer.from(await exported.arrayBuffer()).toString('base64') });
    }
    const combineSource = await readFile(resolve(root, '../iMuse/js/recording-combine-metadata.js'), 'utf8');
    const combine = await import('data:text/javascript;base64,' + Buffer.from(combineSource).toString('base64'));
    const provenance = combine.originalCombineMetadata({ id: f.ID, startedAt: '2026-11-16T09:00:00Z', mimeType: 'audio/mp4' },
        { sampleRate: 48000, channels: 1, packetCount: 1, sampleCount: 960 }, 'original.m4a', () => f.OTHER);
    const combined = await exporter.embedRecordingIdentity(new Blob([f.mp4(), combine.provenanceBox(provenance)]), f.ID);
    if (JSON.stringify(await combine.readCombineMetadata(combined)) !== JSON.stringify(provenance)) throw Error('Combined provenance changed');
    files.push({ name: 'm4a-with-provenance', base64: Buffer.from(await combined.arrayBuffer()).toString('base64') });
    await mkdir(dirname(fixturePath), { recursive: true });
    await writeFile(fixturePath, JSON.stringify({ description: 'Synthetic fixtures generated by actual iMuse v1 exporter; not playable recordings.',
        exporterSha256: createHash('sha256').update(source).digest('hex'), provenanceCodecSha256: createHash('sha256').update(combineSource).digest('hex'), recordingId: f.ID, files }, null, 2) + '\n');
    console.log('Generated 6 reference-exported fixtures; repeated exports, identity readback and combined provenance passed.');
    process.exit(0);
}
if (!process.argv.includes('--browser')) {
    const results = { textContent: '' };
    globalThis.document = { querySelector: () => results, body: { dataset: {} } };
    globalThis.fetch = async relative => {
        const file = resolve(root, 'tests', relative);
        if (!file.startsWith(root + sep)) throw Error('Fixture path outside repository');
        const data = await readFile(file);
        return { json: async () => JSON.parse(data.toString('utf8')), blob: async () => new Blob([data]) };
    };
    await import('./recording-identity.test.js');
    console.log(results.textContent);
    if (globalThis.recordingIdentityTestResult?.failed.length) process.exitCode = 1;
} else {
    let reportResult;
    const report = new Promise(resolve => { reportResult = resolve; });
    const server = createServer(async (request, response) => {
        try {
            if (request.url === '/_identity-test-result' && request.method === 'POST') {
                let body = '';
                for await (const chunk of request) { body += chunk; if (body.length > 100000) throw Error('Oversized test report'); }
                reportResult(JSON.parse(body)); response.end('ok'); return;
            }
            const path = resolve(root, '.' + decodeURIComponent(new URL(request.url, 'http://localhost').pathname));
            if (!path.startsWith(root + sep)) { response.writeHead(403).end(); return; }
            const data = await readFile(path);
            response.setHeader('Content-Type', path.endsWith('.js') ? 'text/javascript' : path.endsWith('.html') ? 'text/html; charset=utf-8' : path.endsWith('.json') ? 'application/json' : 'application/octet-stream');
            response.end(data);
        } catch { response.writeHead(404).end(); }
    });
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const profileRoot = resolve(tmpdir()), profile = await mkdtemp(join(profileRoot, 'memora-recording-identity-'));
    let browser, timer;
    try {
        const edge = process.env.MEMORA_TEST_BROWSER || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
        browser = spawn(edge, ['--headless', '--disable-gpu', '--no-first-run', '--no-default-browser-check',
            '--user-data-dir=' + profile, `http://127.0.0.1:${server.address().port}/tests/recording-identity.html?report=1`], { windowsHide: true, stdio: ['ignore', 'ignore', 'pipe'] });
        let errors = '';
        browser.stderr.on('data', data => { errors = (errors + data).slice(-6000); });
        const stopped = new Promise((_, reject) => {
            browser.once('error', reject);
            browser.once('exit', code => reject(Error('Browser exited before reporting: ' + code + '\n' + errors)));
        });
        const timeout = new Promise((_, reject) => { timer = setTimeout(() => reject(Error('Browser test timed out\n' + errors)), 45000); });
        const result = await Promise.race([report, stopped, timeout]);
        console.log(result.output || JSON.stringify(result));
        if (result.failed?.length || result.error) process.exitCode = 1;
    } finally {
        clearTimeout(timer);
        if (browser && browser.exitCode === null) {
            const exited = new Promise(resolve => browser.once('exit', resolve));
            browser.kill(); await exited;
        }
        server.close();
        // Only remove the exact isolated profile created above, never user data.
        if (dirname(resolve(profile)) === profileRoot && profile.startsWith(join(profileRoot, 'memora-recording-identity-'))) {
            await rm(profile, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }).catch(error => console.warn('Temporary test profile retained:', error.message));
        }
    }
}
